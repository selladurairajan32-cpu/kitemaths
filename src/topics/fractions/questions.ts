export type AssessmentForm = "A" | "B";

const FORM_A = ASSESSMENT_QUESTIONS_A;

type AssessmentItem = FractionQuestion & { area: AssessmentArea };

const AREA_ORDER = (qs: AssessmentItem[]): AssessmentItem[] =>
  [...qs].sort((a, b) => ASSESSMENT_AREAS.indexOf(a.area) - ASSESSMENT_AREAS.indexOf(b.area));

export const ASSESSMENT_FORMS: Record<AssessmentForm, (FractionQuestion & { area: AssessmentArea })[]> = {
  A: AREA_ORDER(FORM_A),
  B: AREA_ORDER(FORM_B),
};

export const ASSESSMENT_QUESTIONS = [...ASSESSMENT_FORMS.A, ...ASSESSMENT_FORMS.B];

export function assessmentItem(id: string): (FractionQuestion & { area: AssessmentArea }) | undefined {
  return ASSESSMENT_QUESTIONS.find((q) => q.id === id);
}

export function formForAttempt(timesCompleted: number, lastForm?: string): AssessmentForm {
  if (lastForm) return lastForm === "A" ? "B" : "A";
  return timesCompleted % 2 === 0 ? "A" : "B";
}

export const ALL_QUESTIONS: FractionQuestion[] = [
  ...PRACTICE_QUESTIONS,
  ...LESSON_QUESTIONS,
  ...FOLLOWUP_QUESTIONS,
  ...ASSESSMENT_QUESTIONS,
];

const byId = new Map(ALL_QUESTIONS.map((q) => [q.id, q]));

export function questionById(id: string): FractionQuestion {
  const q = byId.get(id) ?? (isGeneratedId(id) ? generateFromId(id) : null);
  if (!q) throw new Error(`Unknown question ${id}`);
  return q;
}
